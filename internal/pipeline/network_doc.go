package pipeline

// Network enforcement — честно неисполнимое объявление.
//
// Декларация `permissions.network: [{host: ..., port: ...}]` НЕ фильтруется
// песочницей ни на одной платформе. Исполнимо только `any_host: true` — полный
// egress, который bwrap/шаг помечает как `network: allow`. Структурные списки
// хостов (13→41 примеров) поэтому считаются объявлением, не ограничением:
// валидатор их принимает, раннер пишет warn `network_not_enforceable` и не
// обещает фильтрацию. Человек видит, что ограничение — намерение, не гарантия.
